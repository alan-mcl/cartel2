def replace_in_json(path: Path) -> None:
    data = json.loads(path.read_text())
    changed = False

    def walk(obj):
        nonlocal changed
        if isinstance(obj, dict):
            for k, v in list(obj.items()):
                if k in ("modules",) and isinstance(v, list):
                    obj[k] = [SHIP_MODULE_REPLACE.get(x, x) for x in v]
                    changed = True
                elif isinstance(v, (dict, list)):
                    walk(v)
                elif isinstance(v, str) and v in SHIP_MODULE_REPLACE:
                    obj[k] = SHIP_MODULE_REPLACE[v]
                    changed = True
        elif isinstance(obj, list):
            for i, item in enumerate(obj):
                if isinstance(item, str) and item in SHIP_MODULE_REPLACE:
                    obj[i] = SHIP_MODULE_REPLACE[item]
                    changed = True
                else:
                    walk(item)

    walk(data)
    if changed:
        path.write_text(json.dumps(data, indent=2) + "\n")


def write_json(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2) + "\n")


